"""reports/results.md, rendered from the JSON reports so that no number is typed by hand."""
from __future__ import annotations

import json

from .config import Paths


def _load(paths: Paths, name: str) -> dict:
    return json.loads((paths.reports / name).read_text(encoding="utf-8"))


def _pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f} %"


def _band(b: dict) -> str:
    """Recall for one size band; a band with no injected anomaly has no recall."""
    return "n/a (n=0)" if b["recall"] is None else f"{b['recall']:.2f} (n={b['n']})"


def render_results(paths: Paths) -> str:
    cfg = _load(paths, "run_config.json")
    q = _load(paths, "quality.json")
    an = _load(paths, "anomaly_metrics.json")
    ev = _load(paths, "agent_eval.json")["summary"]
    qual, dbt = q["quality"], q["dbt"]
    inj = qual.get("injected_defects", {})
    L = ["# Results", "",
         "Auto-generated by `carburant run`. **Synthetic data** in the official format: the "
         "numbers describe the simulation, not the real fuel market.", "",
         f"Run: {cfg['stations']} stations, {cfg['days']} days, seed {cfg['seed']}.", "",
         "## Warehouse and data quality", "",
         f"- Price rows staged: {qual['staged_rows']:,}; in the fact table: "
         f"{qual['fact_rows']:,}; quarantined: {qual['quarantined_rows']:,} "
         f"({_pct(qual['quarantined_share'], 2)}). Every staged row is accounted for: "
         f"{'yes' if qual['rows_conserved'] else 'NO'}.",
         "- Quarantine reasons: " + ", ".join(f"{k} {v:,}" for k, v in qual["by_reason"].items())
         + ".",
         f"- dbt build: {dbt['by_type'].get('model', {}).get('success', 0)} models, "
         f"{dbt['n_tests']} data tests ("
         + ", ".join(f"{v} {k}" for k, v in dbt["by_type"].get("test", {}).items()) + ")."]
    if inj:
        L += [f"- Injected defects caught: {inj['caught']:,} / {inj['injected']:,} "
              f"(recall {inj['recall']:.3f}), clean rows wrongly quarantined: "
              f"{inj['false_positives']}. The rules were written for these defect types, so this "
              "shows they work as specified, not that they catch unknown errors."]
    sp = an["split"]
    L += ["", "## Anomaly detection", "",
          f"Anomalies of ±3-20 % injected into {_pct(an['settings']['injection_rate'], 0)} of "
          f"daily prices. Time split: fit {sp['fit_rows']:,} rows, threshold "
          f"{sp['threshold_rows']:,}, test {sp['test_rows']:,} rows "
          f"({sp['test_anomalies']} anomalies).", "",
          "| Detector | Precision [95% CI] | Recall [95% CI] | F1 | PR-AUC | "
          "Recall 3-5 % | Recall 5-10 % | Recall 10-20 % |", "|---|---|---|---|---|---|---|---|"]
    for name, m in an["detectors"].items():
        ci = m["ci95"]
        rb = m["recall_by_magnitude"]
        L.append(f"| {name} | {m['precision']:.2f} [{ci['precision'][0]:.2f}, "
                 f"{ci['precision'][1]:.2f}] | {m['recall']:.2f} [{ci['recall'][0]:.2f}, "
                 f"{ci['recall'][1]:.2f}] | {m['f1']:.2f} | {m['pr_auc']:.2f} | "
                 + " | ".join(_band(rb[b]) for b in rb) + " |")
    cf = an["clean_data_flags"]
    L += ["", f"On the data **without** injected anomalies the rule flags {cf['flagged']:,} of "
          f"{cf['rows']:,} daily prices ({_pct(cf['false_alarm_rate'], 2)}), all false alarms "
          "by construction.", "", "![Anomaly evaluation](anomaly_eval.png)", "",
          "## Agent (RAG + SQL tool)", "",
          f"{ev['n_questions']} held-out questions, expected answers from an independent pandas "
          "oracle. No LLM is called: routing is rule-based.", "",
          "| Kind | Correct | Accuracy |", "|---|---|---|"]
    for k, v in ev["accuracy_by_kind"].items():
        L.append(f"| {k} | {v['correct']} / {v['n']} | {_pct(v['accuracy'], 0)} |")
    L += [f"| **all** | {sum(v['correct'] for v in ev['accuracy_by_kind'].values())} / "
          f"{ev['n_questions']} | **{_pct(ev['accuracy'], 0)}** |", "",
          f"- Answered questions citing a source: {_pct(ev['grounded_rate'], 0)}; out-of-scope "
          f"questions wrongly answered: {ev['hallucinated_out_of_scope']}.",
          f"- Latency (warm, in-process, excludes network): median {ev['latency_ms']['median']} "
          f"ms, p95 {ev['latency_ms']['p95']} ms.", "", "Failures:", ""]
    L += [f"- `{f['id']}` {f['question']} — {f['why']}" for f in ev["failures"]]
    L += ["", "## Dashboard", "",
          "`mart_dashboard` is the table a Looker Studio or Power BI report connects to. "
          "No Looker Studio report was built (no GCP access here); this static view is drawn "
          "from the same table.", "", "![Dashboard](dashboard.png)", ""]
    return "\n".join(L)
